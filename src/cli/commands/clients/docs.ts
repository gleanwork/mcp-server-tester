/**
 * The built-in clients' table in docs/evaluation-framework.md, generated from
 * their definitions, as `mst clients` lists them. `npm run docs:clients`
 * writes it; src/cli/commands/clients/clients.test.ts fails when it differs.
 */
import prettier from 'prettier';
import { listClients } from '../../../evals/builtinClients.js';
import { parseExtensionReference } from '../../../plugins/plugin.js';
import { clientOS } from './index.js';

export const CLIENT_DOCS_FILE = 'docs/evaluation-framework.md';
const START = '<!-- clients:start (generated by `npm run docs:clients`) -->';
const END = '<!-- clients:end -->';

/** The block between the markers, formatted as the docs are. */
export async function clientDocsBlock(): Promise<string> {
  // Built-ins only: a bare reference has no namespace.
  const clients = listClients().filter(
    ([ref]) => parseExtensionReference(ref).namespace === undefined
  );
  const table = [
    '| Client | What it is | Runs on |',
    '| --- | --- | --- |',
    ...clients.map(
      ([ref, definition]) =>
        `| \`${ref}\` | ${definition.description ?? ''} | ${clientOS(definition.requirements ?? {})} |`
    ),
  ];
  const needs = clients.map(([ref, definition]) => {
    const requirements = definition.requirements ?? {};
    const parts = [
      ['Install', requirements.install],
      ['Credentials', requirements.credentials],
      ['Setup', requirements.setup],
    ] as const;
    const said = parts
      .filter(([, lines]) => lines?.length)
      .map(([label, lines]) => `${label}: ${lines!.join('; ')}.`);
    return `- **\`${ref}\`.** ${said.length ? said.join(' ') : 'Nothing beyond MST.'}`;
  });
  const markdown = [
    ...table,
    '',
    'What each one needs on the machine that runs its trials (`mst clients show <client>` prints the same, with its options):',
    '',
    ...needs,
  ].join('\n');
  return (await prettier.format(markdown, { parser: 'markdown' })).trim();
}

/** `docs` with its generated block replaced by `block`. */
export function withClientDocs(docs: string, block: string): string {
  const start = docs.indexOf(START);
  const end = docs.indexOf(END);
  if (start === -1 || end < start)
    throw new Error(`${CLIENT_DOCS_FILE} has no ${START} ... ${END} block.`);
  return `${docs.slice(0, start + START.length)}\n\n${block}\n\n${docs.slice(end)}`;
}
